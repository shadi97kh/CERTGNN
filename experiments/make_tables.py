#!/usr/bin/env python
"""Emit every paper table as a booktabs LaTeX fragment, from committed runs.

Writes one `\\begin{table}...\\end{table}` fragment per table into `paper/tex/`,
each carrying its own caption and label, so the main file only ever `\\input`s
them. A rerun therefore cannot leave a stale number in the paper: the fragment
is regenerated in place and the document picks it up on the next compile.

    python experiments/make_tables.py [--out paper/tex]

Fragments:
    tab_tied.tex       Table 1  accuracy-tied pairs and per-instance agreement
    tab_topk.tex       Table 2  top-k set agreement and concentration
    tab_validation.tex Table 3  the two validation failures, side by side
    tab_full.tex       Table A.2  Tables 1 and 2 combined, with intervals
    tab_protocol.tex   Table A.3  per-cell protocol from tuning_budget.json

Nothing here is hardcoded. Runs are resolved by experiment name plus the fields
each table needs, and a run that lacks one is rejected loudly rather than
quietly dropping a column.
"""

from __future__ import annotations

import argparse
import glob
import json
import pathlib
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[1]
RUNS = ROOT / "results" / "runs"

NEEDS: dict[str, tuple[str, ...]] = {
    "occurrence": (
        "hidden",
        "depth",
        "heldout_r2_mean",
        "n_pairs_total",
        "n_pairs_indistinguishable",
        "pooled_mde_r2",
        "pooled_pi_p10",
        "pooled_pi_median",
        "pooled_pi_frac_below_05",
        "pooled_conc_top3",
        "pooled_eff_pos",
        "pooled_tk_ex3",
        "pooled_tk_j3",
    ),
    "closure_search": ("hidden", "depth", "arm1_cold_heldout"),
    "closure_heldout": ("hidden", "depth"),
    "separation": ("hidden", "depth", "n_separate"),
}


# ------------------------------------------------------------------ resolution


def _usable(run: pathlib.Path, experiment: str, keys: tuple[str, ...]) -> str | None:
    if not (run / "meta.json").exists() or not (run / "results.json").exists():
        return "missing meta.json or results.json"
    try:
        meta = json.load(open(run / "meta.json"))
        res = json.load(open(run / "results.json"))
    except Exception as exc:  # noqa: BLE001
        return f"unreadable: {exc}"
    if meta.get("experiment") != experiment:
        return "different experiment"
    if res.get("dump_only"):
        return "dump_only run (partial grid)"
    cells = res.get("cells") or {}
    if len(cells) < 12:
        return f"partial grid ({len(cells)} cells)"
    for name, cell in cells.items():
        miss = [k for k in keys if k not in cell]
        if miss:
            return f"cell {name} lacks {', '.join(miss)}"
    return None


def resolve(experiment: str) -> pathlib.Path:
    cands = []
    for run in sorted(RUNS.glob("*/")):
        if _usable(run, experiment, NEEDS[experiment]) is None:
            meta = json.load(open(run / "meta.json"))
            cands.append(
                (meta.get("timestamp_utc", ""), bool(meta.get("git_dirty")), run)
            )
    if not cands:
        raise SystemExit(f"no committed {experiment} run carries every needed field")
    clean = [c for c in cands if not c[1]]
    return max(clean or cands, key=lambda c: c[0])[2]


def cells_of(run: pathlib.Path) -> dict:
    return json.load(open(run / "results.json"))["cells"]


def order(cells: dict) -> list[str]:
    return sorted(cells, key=lambda k: (cells[k]["hidden"], cells[k]["depth"]))


# The main-text tables show the two extreme widths at every depth. That
# brackets the grid on both axes the paper argues about -- capacity and depth --
# and includes 128x1, the best-fitting cell the "not weak models" claim rests
# on. All twelve cells are in Table A.2, so nothing is hidden, and the caption
# says which rule selected these. Twelve-row tables in the body cost roughly a
# page each and push the floats past the references.
MAIN_CELLS = ("16x1", "16x2", "16x3", "128x1", "128x2", "128x3")


def main_order(cells: dict) -> list[str]:
    keep = [k for k in order(cells) if k in MAIN_CELLS]
    return keep or order(cells)


def meta_of(run: pathlib.Path) -> dict:
    return json.load(open(run / "meta.json"))


# --------------------------------------------------------------------- helpers


def fragment(
    body: list[str],
    colspec: str,
    header: str,
    caption: str,
    label: str,
    placement: str = "!tb",
    small: bool = True,
) -> str:
    L = [
        "% Generated by experiments/make_tables.py -- do not edit by hand.",
        f"\\begin{{table}}[{placement}]",
        "  \\centering",
    ]
    if small:
        L.append("  \\small")
    # Shrink to the text block only if the table would otherwise overrun it.
    # \resizebox with this \ifdim guard is a no-op for tables that already fit,
    # so narrow tables keep their normal type size and only the wide ones scale.
    L += [
        "  \\resizebox{\\ifdim\\width>\\linewidth\\linewidth\\else\\width\\fi}{!}{%",
        f"  \\begin{{tabular}}{{{colspec}}}",
        "    \\toprule",
        f"    {header} \\\\",
        "    \\midrule",
    ]
    L += [f"    {r} \\\\" for r in body]
    # Caption BELOW the tabular, matching the figures.
    L += [
        "    \\bottomrule",
        "  \\end{tabular}}",
        f"  \\caption{{{caption}}}",
        f"  \\label{{{label}}}",
        "\\end{table}",
        "",
    ]
    return "\n".join(L)


def ci(e: dict, fmt: str = "{:.4f}") -> str:
    return (
        fmt.format(e["mean"])
        + " \\tiny["
        + fmt.format(e["lo"])
        + ", "
        + fmt.format(e["hi"])
        + "]"
    )


def mathnum(x: float, fmt: str = "{:,.0f}") -> str:
    """Thousands separator that is safe inside math mode.

    A bare comma in math mode is punctuation, not a digit separator, and TeX
    spaces it accordingly. `{,}` is the standard fix.
    """
    return fmt.format(x).replace(",", "{,}")


def pct(x: float) -> str:
    return f"{x * 100:.0f}\\%"


# ------------------------------------------------------------------- table 1/2


def table_tied(occ: pathlib.Path) -> str:
    c = cells_of(occ)
    body = []
    for k in main_order(c):
        e = c[k]
        body.append(
            f"{e['hidden']}$\\times${e['depth']} & "
            f"{e['heldout_r2_mean']['mean']:.4f} & "
            f"{e['n_pairs_indistinguishable']['mean']:.0f}/"
            f"{e['n_pairs_total']['mean']:.0f} & "
            f"{e['pooled_mde_r2']:.4f} & "
            f"{e['pooled_pi_p10']:+.3f} / {e['pooled_pi_median']:+.3f} & "
            f"{pct(e['pooled_pi_frac_below_05'])}"
        )
    cap = (
        r"\textbf{Models the held-out data cannot tell apart still rank a "
        r"sequence's positions differently.} Accuracy-tied pairs and their "
        r"attribution agreement. A pair is \emph{tied} when a paired two-sided "
        r"$t$-test on per-point held-out squared errors does not reject at "
        r"$\alpha = 0.05$; \emph{resolution} is the smallest held-out $R^2$ gap "
        r"that test could have detected at $80\%$ power, so a tie is a failure "
        r"to reject at a stated resolution rather than a claim of equality. "
        r"Per-instance $\rho$ is a Spearman correlation between two models' "
        r"9-position attribution vectors \emph{for a single held-out sequence}, "
        r"pooled over sequences and over tied pairs. \textbf{Rows are the two "
        r"extreme widths at each depth}, which bracket both axes the argument "
        r"turns on; all twelve cells, with bootstrap intervals, are in "
        r"Table~\ref{tab:full}."
    )
    return fragment(
        body,
        "lrrrrr",
        r"cell & held-out $R^2$ & tied pairs & resolution ($\Delta R^2$) & "
        r"$\rho$ p10 / median & frac $\rho<0.5$",
        cap,
        "tab:tied",
    )


def table_topk(occ: pathlib.Path) -> str:
    c = cells_of(occ)
    body = []
    for k in main_order(c):
        e = c[k]
        body.append(
            f"{e['hidden']}$\\times${e['depth']} & "
            f"{e['pooled_conc_top3']:.3f} & "
            f"{e['pooled_eff_pos']:.2f} & "
            f"{pct(1 - e['pooled_tk_ex1'])} & "
            f"{pct(e['pooled_tk_ex3'])} & "
            f"{e['pooled_tk_j3']:.2f}"
        )
    cap = (
        r"\textbf{The disagreement is about which positions carry the mass, not "
        r"about the ordering of a negligible tail.} Top-3 set agreement and "
        r"attribution concentration. \emph{top-3 mass} is the median fraction "
        r"of a sequence's total $|\Delta|$ in its three strongest positions and "
        r"\emph{effective positions} is $\exp$ of the entropy of the normalized "
        r"magnitudes, where $9$ means all positions contribute equally. Jaccard "
        r"on 3-element sets takes only $\{0, 0.2, 0.5, 1\}$, so its median is "
        r"near-useless as a summary and the \emph{mean} is reported, alongside "
        r"the fraction of sequences whose top-3 sets match exactly. \textbf{top-1 "
        r"differs} is the fraction of sequences on which the two models' single "
        r"\emph{strongest} position is a different position --- a stronger form "
        r"of disagreement than a reordering beneath a shared leader, and not "
        r"implied by the top-3 columns, which are over unordered sets. Rows are "
        r"the same bracketing subset as Table~\ref{tab:tied}; all twelve cells "
        r"are in Table~\ref{tab:full}."
    )
    return fragment(
        body,
        "lrrrrr",
        r"cell & top-3 mass & effective positions & top-1 differs & "
        r"top-3 exact match & mean Jaccard",
        cap,
        "tab:topk",
    )


# --------------------------------------------------------------------- table 3


def table_validation(cs: pathlib.Path, sep: pathlib.Path) -> str:
    c = cells_of(cs)
    worst = min(c, key=lambda k: c[k]["arm1_cold_heldout"]["mean"])
    worst_v = c[worst]["arm1_cold_heldout"]["mean"]
    below = sum(1 for k in c if c[k]["arm1_cold_heldout"]["mean"] < 0.999)
    z = [v["n_separate"]["mean"] for v in cells_of(sep).values()]

    rows = [
        (
            r"\textbf{Ceiling control}",
            r"Held-out $R^2 = 1.000000$ recovering a target the architecture "
            r"realizes exactly, in every cell and every seed.",
            r"That Adam does not leave a perfect solution. Warm-started "
            r"\emph{at} the target, its initial loss was already below the "
            r"stopping threshold and best-iterate selection kept the initial "
            r"state, so the loop never ran.",
            rf"Cold-started on the same target, the worst cell reaches only "
            rf"${worst_v:.4f}$ and {below} of {len(c)} cells fall below the "
            rf"$0.999$ threshold.",
        ),
        (
            r"\textbf{Noise model}",
            r"A required sample size of zero: any two fits separable with no "
            r"data at all.",
            r"Inverse-variance weighting under a count model undefined on "
            r"this library: the pools are not a proportion, "
            r"$\mathrm{ex} \ge \mathrm{tot}$ on $4.9\%$ of rows, so binomial "
            r"variance is zero or negative there and a few near-saturated "
            r"sequences carried the statistic.",
            rf"Under the Poisson log-ratio the weights are ordinary (mean "
            rf"$1/\sigma^2$ is $3.0\times$ its median) and the requirement is "
            rf"finite, ${min(z):.1f}$ to ${mathnum(max(z))}$ measurements.",
        ),
    ]
    body = [" & ".join(r) for r in rows]
    cap = (
        r"\textbf{Both controls we relied on were passing for reasons "
        r"unrelated to what they were meant to test.} Neither failure was "
        r"visible from the reported number alone: a control that cannot fail "
        r"and a weighting scheme that silently concentrates on a few points "
        r"both look like success."
    )
    return fragment(
        body,
        "p{0.10\\linewidth}p{0.24\\linewidth}p{0.30\\linewidth}p{0.28\\linewidth}",
        r"check & what it reported & what it actually tested & corrected control",
        cap,
        "tab:validation",
        small=True,
    )


# ------------------------------------------------------------------- table A.2


def table_full(occ: pathlib.Path) -> str:
    c = cells_of(occ)
    body = []
    for k in order(c):
        e = c[k]
        body.append(
            f"{e['hidden']}$\\times${e['depth']} & "
            f"{ci(e['heldout_r2_mean'])} & "
            f"{ci(e['n_pairs_indistinguishable'], '{:.0f}')} & "
            f"{e['pooled_mde_r2']:.4f} & "
            f"{e['pooled_pi_p10']:+.3f} / {e['pooled_pi_median']:+.3f} & "
            f"{pct(e['pooled_pi_frac_below_05'])} & "
            f"{e['pooled_conc_top3']:.3f} & "
            f"{e['pooled_eff_pos']:.2f} & "
            f"{pct(1 - e['pooled_tk_ex1'])} & "
            f"{pct(e['pooled_tk_ex3'])} & "
            f"{e['pooled_tk_j3']:.2f}"
        )
    cap = (
        r"\textbf{No cell is withheld: the pattern in Tables~\ref{tab:tied} "
        r"and~\ref{tab:topk} holds across the whole grid.} All twelve cells, "
        r"combining both main-text tables. \textbf{Which columns carry "
        r"intervals, and why the rest do not:} held-out $R^2$ and the tied-pair "
        r"count are per-seed quantities and are given as mean with a $95\%$ "
        r"bootstrap interval over the ten seeds. The remaining columns are "
        r"medians pooled over every tied pair across all seeds rather than "
        r"per-seed values, so a seed-level bootstrap interval is not defined "
        r"for them and none is invented here."
    )
    return fragment(
        body,
        "lllrrrrrrrr",
        r"cell & held-out $R^2$ & tied pairs & res.\ & $\rho$ p10 / med & "
        r"$\rho{<}0.5$ & top-3 mass & eff.\ pos & top-1 diff & exact & Jaccard",
        cap,
        "tab:full",
        placement="!htb",
    )


# ------------------------------------------------------------------- table A.3


def table_protocol(occ: pathlib.Path) -> str:
    tb = {r["model"]: r for r in json.load(open(occ / "tuning_budget.json"))}
    lr: dict[str, list[float]] = {}
    for f in sorted(glob.glob(str(occ / "seed_*.json"))):
        d = json.load(open(f))
        for e in d["cells"]:
            lr.setdefault(f"{e['hidden']}x{e['depth']}", []).append(float(e["lr"]))
    c = cells_of(occ)
    body, varies = [], 0
    for k in order(c):
        e = c[k]
        vals = Counter(lr.get(k, []))
        if len(vals) > 1:
            varies += 1
            chosen = ", ".join(
                f"{v:g} ($\\times${n})" for v, n in sorted(vals.items(), reverse=True)
            )
        else:
            chosen = f"{next(iter(vals)):g}" if vals else "--"
        t = tb.get(f"neural_{k}", {})
        body.append(
            f"{e['hidden']}$\\times${e['depth']} & {chosen} & "
            f"{t.get('configs_tried', '--')} & {int(t.get('epochs', 0)):,} & "
            f"{int(t.get('gradient_steps', 0)):,}"
        )
    sel = next(iter({r["selection"] for r in tb.values()}), "")
    space = next(iter({r["search_space"] for r in tb.values()}), "")
    cap = (
        r"\textbf{The tuning budget is four learning rates per cell and nothing "
        r"else, so the disagreement cannot be an artifact of unequal search.} "
        r"Per-cell protocol, read from \texttt{tuning\_budget.json} and the "
        r"per-seed records. The search space is "
        rf"``{space}''. The selection rule is identical in every cell --- "
        rf"``{sel}'' --- so it is stated here rather than repeated as a column. "
        rf"\textbf{{The chosen rate is not constant across seeds:}} it varies in "
        rf"{varies} of {len(c)} cells, and the multiplicities are given. Within "
        r"any one seed a single rate is shared by all 20 models in the cell, so "
        r"the models still differ only in initialization; across seeds the rate "
        r"is re-selected."
    )
    return fragment(
        body,
        "lllrr",
        r"cell & learning rate chosen (seeds) & configs & epochs & grad.\ steps",
        cap,
        "tab:protocol",
        placement="!htb",
    )


# ----------------------------------------------------------------------- main


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="paper/tex")
    args = ap.parse_args()
    out = pathlib.Path(args.out)
    if not out.is_absolute():
        out = ROOT / out
    out.mkdir(parents=True, exist_ok=True)

    occ = resolve("occurrence")
    cs = resolve("closure_search")
    sep = resolve("separation")
    for tag, run in (("occurrence", occ), ("closure_search", cs), ("separation", sep)):
        m = meta_of(run)
        print(f"  {tag:16} {run.name}  sha={m['git_sha']} cfg={m['config_hash']}")

    frags: dict[str, str] = {
        "tab_tied.tex": table_tied(occ),
        "tab_topk.tex": table_topk(occ),
        "tab_validation.tex": table_validation(cs, sep),
        "tab_full.tex": table_full(occ),
        "tab_protocol.tex": table_protocol(occ),
    }
    for name, text in frags.items():
        (out / name).write_text(text)
        rows = text.count("\\\\") - 1
        print(f"  wrote {out.name}/{name:20} ({rows} body rows)")

    prov = {
        "occurrence": meta_of(occ) | {"run": occ.name},
        "closure_search": meta_of(cs) | {"run": cs.name},
        "separation": meta_of(sep) | {"run": sep.name},
        "fragments": sorted(frags),
    }
    (out / "PROVENANCE.json").write_text(json.dumps(prov, indent=2))
    print(f"  wrote {out.name}/PROVENANCE.json")


if __name__ == "__main__":
    main()
